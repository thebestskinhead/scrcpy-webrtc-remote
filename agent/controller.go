// Device state constants for the controller's state machine.
const (
	deviceIdle int32 = 0 // No active WebRTC connection
	deviceBusy int32 = 1 // WebRTC connection is active
)

const (
	eventQueueSize = 32  // Buffer size for per-session event channels
	maxSessions    = 5   // Maximum concurrent session contexts
	preemptTimeout = 10 * time.Second
)

const (
	heartbeatIntervalSec = 30   // WebSocket 心跳间隔（秒）
	retryFastAttempts    = 12   // 快速重连次数（间隔 5s）
	retryFastInterval    = 5 * time.Second
	retrySlowInterval    = 5 * time.Minute // 之后的慢速重连间隔
)

// SessionCtx holds all state for one browser connection.
// Each browser WebSocket gets its own SessionCtx with an
// independent goroutine processing events sequentially.
type SessionCtx struct {
	id         string
	stopChan   chan struct{}       // Closed to signal preemption / stop
	eventQueue chan common.WsMsg   // Ordered event channel from main loop
	done       chan struct{}       // Closed when cleanup completes

	peer    *bridgewebrtc.PeerManager
	mgr     *gateway.Manager
	ctrl    *Controller // back-reference for quality tier persistence

	// session is assigned asynchronously by prepareSession (offer handling
	// no longer blocks on scrcpy startup). Guard with mu; sessionReady is
	// closed once the session is Streaming and media can flow.
	mu           sync.Mutex
	session      *gateway.Session
	sessionReady chan struct{}
	// prepareOnce guards prepareSession against duplicate offers: a browser
	// reconnect may deliver two offers to the same SessionCtx, and two
	// concurrent prepareSession goroutines would both close(sessionReady)
	// → "close of closed channel" panic (observed 2026-08-14).
	prepareOnce sync.Once

	// pendingCandidates buffers trickled ICE candidates that arrive before
	// the peer is created (the peer waits for the scrcpy session, which can
	// take several seconds). Dropping them would lose the browser's early
	// host/srflx candidates and prevent NAT pinholing on the direct path.
	pendingCandidates []*common.IceCandidate

	ws   *Client
	inst config.InstanceConfig

	// ICE servers snapshot taken at session creation time
	signalingSTUN []string
	signalingTURN *config.TurnServerConfig

	// Shared device state pointer (set by Controller)
	deviceState *atomic.Int32

	// Per-session bitrate hysteresis
	initialBitrate    int
	lastBitrate       int
	lastBitrateChange time.Time
	lastLossLowTime   time.Time // start of sustained low-loss period for recovery

	// Bitrate floor (configurable, default 400 kbps). Prevents loss-based BWE
	// from driving the encoder into a zombie stream (30 kbps is unusable for
	// cloud gaming;宁可断开也不要僵尸流).
	minBitrate int

	// Track the magnitude of the last bitrate drop to detect overly
	// aggressive BWE reactions.
	lastBitrateDropPct float64

	// preemptedByForce 标记本会话是被 ForceCloseSession / relay preempt
	// 强制结束的（而非浏览器主动 unbound）。用于抑制随后 signaling 的
	// unbound 消息重复上报 user_unbound 事件（竞态见 preemptAndWait）。
	preemptedByForce atomic.Bool

	// debug is the optional debug extension hook (nil in open-source
	// builds; a closed-source Hooks implementation is injected by the
	// platform binary). All debug protocol handling, metric sampling and
	// weak-network simulation live behind this nil-checked interface.
	debug debughooks.Hooks
}

// Controller is the agent-side orchestrator for one device instance.
// It routes messages from signaling to the correct SessionCtx goroutine
// and manages the lifecycle of all sessions (create, preempt, cleanup).
// 平台化后每个设备一个 Controller，由 DeviceManager 管理；配置经 ConfigStore
// 惰性读取（ReloadConfig 对新会话生效，不中断现有会话）。
type Controller struct {
	store *ConfigStore
	inst  config.InstanceConfig
	ws    *Client
	wsMu  sync.Mutex // guards ws (written by runOnce, closed by Stop)
	pool  *portpool.Pool
	adbCli *adb.Client

	manager *gateway.Manager

	// connectParams 覆盖信令连接参数（PrepareDevice.connect_params）。
	connectParams ConnectParams

	// Session management — map keyed by session_id (generated by signaling)
	sessions         map[string]*SessionCtx
	currentSessionID string
	mu               sync.Mutex

	// ICE servers received from signaling (shared, applied to new sessions)
	signalingSTUN []string
	signalingTURN *config.TurnServerConfig

	// Device state machine: Idle (no active connection) or Busy (WebRTC connected)
	deviceState atomic.Int32

	// signalingConnected tracks the signaling WS liveness, observable via
	// ListDevices.signaling_connected.
	signalingConnected atomic.Bool
	// registeredAt is set on each successful connect (for connected_seconds).
	registeredAt atomic.Int64 // unix seconds

	// stopChan closes to make Run's reconnect loop exit (Release/Reset/Stop).
	stopChan chan struct{}

	// qualityBitrate is the user-selected quality tier (bps), persisted at
	// controller level so reconnects and new sessions inherit it.
	// 0 means "not explicitly selected" → use scrcpy.video_bit_rate (原画).
	qualityBitrate atomic.Int64

	// hooks 是平台事件上报扩展点（nil 即禁用，见 hooks.go）。
	hooks PlatformHooks

	// debug is the optional debug extension hook propagated to every
	// SessionCtx. nil in open-source builds.
	debug debughooks.Hooks
}

// SetDebugHooks injects the optional debug extension (closed-source).
// Passing nil disables all debug functionality. Must be called before Run.
func (c *Controller) SetDebugHooks(h debughooks.Hooks) {
	c.debug = h
}

// NewSharedPortPool creates a port pool that should be shared across all
// controller instances to prevent ADB forward port conflicts on the host.
func NewSharedPortPool(start, size int) *portpool.Pool {
	return portpool.New(start, size)
}

// AutoConnectDevices checks each configured device against `adb devices`
// and runs `adb connect` for any TCP/IP device not yet connected.
func AutoConnectDevices(agentCfg config.AgentConfig, instances []config.InstanceConfig) {
	adbCli := adb.New(agentCfg.ADBPath)
	connected, err := adbCli.Devices()
	if err != nil {
		logger.Warn("adb devices failed, skipping auto-connect", "err", err)
		return
	}
	connectedSet := make(map[string]bool, len(connected))
	for _, s := range connected {
		connectedSet[s] = true
	}
	for _, inst := range instances {
		if connectedSet[inst.DeviceSerial] {
			continue
		}
		if !strings.Contains(inst.DeviceSerial, ":") {
			// USB devices (no port) expected to be connected by cable
			continue
		}
		logger.Info("adb connecting device", "serial", inst.DeviceSerial)
		if err := adbCli.Connect(inst.DeviceSerial); err != nil {
			logger.Warn("adb connect failed, device may be unavailable",
				"serial", inst.DeviceSerial, "err", err)
		} else {
			logger.Info("adb connect succeeded", "serial", inst.DeviceSerial)
		}
	}
}

// newController creates a controller backed by a ConfigStore (sidecar path).
// 修复历史 bug：adb 可执行路径取配置的 adb_path，而非硬编码 "adb"。
func newController(store *ConfigStore, inst config.InstanceConfig, pool *portpool.Pool, hooks PlatformHooks, cp ConnectParams) *Controller {
	cfg := store.ForDevice(inst.DeviceSerial)
	adbCli := adb.New(cfg.ADBPath)
	manager := gateway.NewManager(adbCli, pool, cfg.Scrcpy)

	return &Controller{
		store:         store,
		inst:          inst,
		pool:          pool,
		adbCli:        adbCli,
		manager:       manager,
		connectParams: cp,
		sessions:      make(map[string]*SessionCtx),
		stopChan:      make(chan struct{}),
		hooks:         hooks,
	}
}

// Config returns the current effective config (global + this device's
// per-device overrides), re-read on each call so ReloadConfig takes effect
// for new sessions without interrupting active ones.
func (c *Controller) Config() config.AgentConfig {
	if cfg := c.store.ForDevice(c.inst.DeviceSerial); cfg != nil {
		return *cfg
	}
	return config.AgentConfig{}
}

// SignalingConnected reports whether the signaling WS is currently alive.
func (c *Controller) SignalingConnected() bool {
	return c.signalingConnected.Load()
}

// SetPlatformHooks injects the platform event hooks (nil disables).
func (c *Controller) SetPlatformHooks(h PlatformHooks) {
	c.hooks = h
}

// SetConnectParams overrides the signaling connection params.
func (c *Controller) SetConnectParams(cp ConnectParams) {
	c.connectParams = cp
}

// reportDeviceStatus pushes a DeviceStatusChanged event for this device
// (busy state, used both on connect and on explicit status changes).
func (c *Controller) reportDeviceStatus() {
	if c.hooks == nil {
		return
	}
	c.hooks.OnDeviceStatus(c.inst.DeviceSerial, c.inst.InstanceID, c.deviceState.Load() == deviceBusy)
}

// setSignalingDown resets signaling state and reports the disconnection
// (AgentError code ERR_SIGNALING_DISCONNECTED). 所有管理 RPC 均为本地操作、
// 不依赖信令在线，因此该码只经 AgentError 事件上报（见 PLATFORM-API.md §7）。
// 首次连接失败（如不可达 signaling_url 配置）同样上报，供测试与平台观测。
func (c *Controller) setSignalingDown(err error) {
	c.signalingConnected.Store(false)
	c.registeredAt.Store(0)
	if c.hooks != nil {
		c.hooks.OnError(c.inst.DeviceSerial, c.inst.InstanceID,
			"ERR_SIGNALING_DISCONNECTED", err.Error())
		c.hooks.OnDeviceStatus(c.inst.DeviceSerial, c.inst.InstanceID,
			c.deviceState.Load() == deviceBusy)
	}
}

// Stop tears the controller down: closes the signaling WS (unblocks runOnce),
// closes the reconnect loop, and stops all sessions. Idempotent.
func (c *Controller) Stop() {
	select {
	case <-c.stopChan:
		// already stopped
	default:
		close(c.stopChan)
	}
	c.wsMu.Lock()
	if c.ws != nil {
		_ = c.ws.Close()
	}
	c.wsMu.Unlock()
	c.shutdownAll()
	c.signalingConnected.Store(false)
}

// CurrentSession returns the active SessionCtx (nil when idle).
func (c *Controller) CurrentSession() *SessionCtx {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.sessions[c.currentSessionID]
}

// CurrentSessionID returns the active session id ("" when idle).
func (c *Controller) CurrentSessionID() string {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.currentSessionID
}

// Busy reports whether a WebRTC session is active.
func (c *Controller) Busy() bool {
	return c.deviceState.Load() == deviceBusy
}

// ConnectedSeconds returns the elapsed time of the current signaling
// connection (0 when disconnected).
func (c *Controller) ConnectedSeconds() int32 {
	start := c.registeredAt.Load()
	if start == 0 {
		return 0
	}
	sec := time.Now().Unix() - start
	if sec < 0 {
		return 0
	}
	return int32(sec)
}

// ForceCloseSession forcibly closes the session (absolute management right):
// the old browser gets a preempted message and the SessionCtx is stopped.
// reason 透传到 SessionStopped 事件的 reason 字段（空则默认 "forced"）。
// Returns an error when the session_id is unknown (ERR_SESSION_NOT_FOUND).
func (c *Controller) ForceCloseSession(sessionID, reason string) error {
	c.mu.Lock()
	ctx := c.sessions[sessionID]
	c.mu.Unlock()
	if ctx == nil {
		return fmt.Errorf("session not found")
	}
	if reason == "" {
		reason = "forced"
	}
	logger.Info("force close session (platform)",
		"session_id", sessionID, "serial", c.inst.DeviceSerial, "reason", reason)
	c.preemptAndWait(ctx, sessionID, reason)
	return nil
}

// SetQuality persists the quality tier and applies it to an active session
// (through the session event queue to stay race-free with the bitrate ladder).
// 无会话时仅持久化，后续会话继承该档位（见 PLATFORM-API.md §3.8）。
func (c *Controller) SetQuality(level string) error {
	switch level {
	case "clear", "hd", "original":
	default:
		return fmt.Errorf("invalid quality level: %q", level)
	}
	bitrate := c.tierBitrate(c.Config(), level)
	c.qualityBitrate.Store(int64(bitrate))

	if ctx := c.CurrentSession(); ctx != nil {
		select {
		case ctx.eventQueue <- common.WsMsg{Type: "set_quality", Data: map[string]any{"level": level}}:
		default:
			logger.Warn("set_quality dropped: event queue full", "session_id", ctx.id)
		}
	}
	return nil
}

// SendControlRaw forwards a platform-issued control message to the active
// session's scrcpy (fire-and-forget, 见 PLATFORM-API.md §3.9)。无活动会话时
// 静默成功，不做缓存。
func (c *Controller) SendControlRaw(ctrlType string, data map[string]any) error {
	if ctrlType == "" {
		return fmt.Errorf("missing control type")
	}
	ctx := c.CurrentSession()
	if ctx == nil {
		return nil
	}
	ctx.dispatchControl(ctrlType, data)
	return nil
}

// Run is the top-level event loop for this device instance. It connects to
// the signaling server and retries indefinitely when the WebSocket drops:
//
//	attempts 1–12: every 5 seconds
//	attempts 13+:  every 5 minutes
//
// Close the controller via Stop() to exit the retry loop.
func (c *Controller) Run() {
	attempts := 0
	for {
		if err := c.runOnce(); err != nil {
			logger.Warn("signaling connection lost, retrying",
				"instance", c.inst.InstanceID,
				"attempt", attempts+1,
				"err", err)
		}
		attempts++
		select {
		case <-c.stopChan:
			logger.Info("controller stopped", "instance", c.inst.InstanceID,
				"serial", c.inst.DeviceSerial)
			return
		case <-time.After(backoffDelay(attempts)):
		}
	}
}

// backoffDelay returns the sleep duration before the next reconnect attempt.
// First retryFastAttempts attempts: retryFastInterval. Beyond that: retrySlowInterval.
func backoffDelay(attempt int) time.Duration {
	if attempt <= retryFastAttempts {
		return retryFastInterval
	}
	return retrySlowInterval
}

// runOnce connects to signaling, starts the heartbeat, and enters the
// main message loop. Returns on any unrecoverable error (e.g. WS read failure).
func (c *Controller) runOnce() error {
	cfg := c.Config()
	ws, err := ConnectWithParams(cfg.SignalingURL, cfg.ServiceID,
		c.inst.InstanceID, c.inst.DeviceSerial, c.connectParams)
	if err != nil {
		// 信令连接失败：上报 AgentError + 状态复位（可经不可达 signaling_url 配置触发）。
		c.setSignalingDown(err)
		return fmt.Errorf("connect to signaling: %w", err)
	}
	c.wsMu.Lock()
	c.ws = ws
	c.wsMu.Unlock()
	defer ws.Close()

	c.signalingConnected.Store(true)
	c.registeredAt.Store(time.Now().Unix())
	c.reportDeviceStatus()

	// Background heartbeat to keep the WebSocket alive through proxies.
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	ws.Heartbeat(ctx, time.Duration(heartbeatIntervalSec)*time.Second)

	logger.Info("agent instance connected",
		"service", cfg.ServiceID,
		"instance", c.inst.InstanceID,
		"serial", c.inst.DeviceSerial)

	// Stop() closes the WS to unblock the blocking Read below; on any return
	// from runOnce (ws drop, Stop, connect failure) reset signaling state.
	defer c.setSignalingDown(fmt.Errorf("signaling connection closed"))

	// Main message loop — routes messages to SessionCtx goroutines
	for {
		msg, err := ws.Read()
		if err != nil {
			c.shutdownAll()
			return fmt.Errorf("ws read: %w", err)
		}

		switch msg.Type {
		case common.TypeBound:
			logger.Info("browser bound", "instance", c.inst.InstanceID,
				"session_id", msg.SessionID)
			if err := c.handleBound(msg); err != nil {
				logger.Error("handle bound failed", "err", err)
				c.shutdownAll()
				return err
			}

		case common.TypeUnbound:
			logger.Info("browser unbound", "instance", c.inst.InstanceID,
				"session_id", msg.SessionID)
			c.handleUnbound(msg)

		case common.TypeIceServers:
			// Shared across sessions — store in Controller
			c.signalingSTUN = nil
			c.signalingTURN = nil
			for _, e := range msg.IceServers {
				urls := make([]string, len(e.URLs))
				copy(urls, e.URLs)
				if e.Username == "" && e.Credential == "" {
					c.signalingSTUN = append(c.signalingSTUN, urls...)
				} else {
					if c.signalingTURN == nil {
						c.signalingTURN = &config.TurnServerConfig{
							URLs: urls, Username: e.Username, Credential: e.Credential,
						}
					}
				}
			}
			logger.Info("received ICE servers from signaling",
				"stun", len(c.signalingSTUN), "turn", c.signalingTURN != nil,
				"ttl", msg.TTL)

		case "relay":
			// Generic relay message from browser via signaling.
			if msg.Payload == nil || msg.RelayID == "" {
				continue
			}
			innerType, _ := msg.Payload["type"].(string)
			switch innerType {
			case "query_status":
				busy := c.deviceState.Load() == deviceBusy
				c.ws.Send(common.WsMsg{
					Type:    "relay",
					RelayID: msg.RelayID,
					Payload: map[string]any{
						"type": "status_resp",
						"busy": busy,
					},
				})
			case "preempt":
				c.handleRelayPreempt(msg)
			}

		case common.TypePong:
			// heartbeat reply from signaling — silently ignore
			continue

		default:
			// Route to SessionCtx by session_id
			if msg.SessionID == "" {
				logger.Warn("message without session_id, dropping",
					"type", msg.Type)
				continue
			}
			c.routeToSession(msg)
		}
	}
}

// ---------------------------------------------------------------------------
// Session lifecycle: Bound / Unbound
// ---------------------------------------------------------------------------

// handleBound creates a new SessionCtx and starts its goroutine.
// If another session is active, it preempts the old one first.
func (c *Controller) handleBound(msg common.WsMsg) error {
	sessionID := msg.SessionID
	if sessionID == "" {
		return fmt.Errorf("bound without session_id")
	}

	// Check session limit
	c.mu.Lock()
	if len(c.sessions) >= maxSessions {
		c.mu.Unlock()
		logger.Warn("too many sessions, rejecting bound", "session_id", sessionID)
		return fmt.Errorf("max sessions (%d) reached", maxSessions)
	}

	// If a different session is active, preempt it
	oldID := c.currentSessionID
	oldCtx := c.sessions[oldID]
	c.mu.Unlock()

	if oldID != "" && oldID != sessionID && oldCtx != nil {
		logger.Warn("preempting existing session for new connection",
			"old_session", oldID, "new_session", sessionID)
		c.preemptAndWait(oldCtx, oldID, "forced")
	}

	// Create new SessionCtx
	ctx := c.newSessionCtx(sessionID)

	c.mu.Lock()
	c.sessions[sessionID] = ctx
	c.currentSessionID = sessionID
	c.mu.Unlock()

	go ctx.run()
	logger.Info("session context created", "session_id", sessionID)

	if c.hooks != nil {
		c.hooks.OnSessionStarted(c.inst.DeviceSerial, c.inst.InstanceID, sessionID)
	}
	return nil
}

// handleUnbound signals the target SessionCtx to stop and waits for cleanup.
func (c *Controller) handleUnbound(msg common.WsMsg) {
	sessionID := msg.SessionID
	if sessionID == "" {
		logger.Warn("unbound without session_id")
		return
	}

	c.mu.Lock()
	ctx := c.sessions[sessionID]
	c.mu.Unlock()

	if ctx == nil {
		logger.Warn("unbound for unknown session", "session_id", sessionID)
		return
	}

	logger.Info("stopping session", "session_id", sessionID)

	// Signal stop (idempotent via select)
	select {
	case <-ctx.stopChan:
		// already stopped
	default:
		close(ctx.stopChan)
	}

	// Wait for cleanup
	<-ctx.done

	c.mu.Lock()
	delete(c.sessions, sessionID)
	if c.currentSessionID == sessionID {
		c.currentSessionID = ""
	}
	c.mu.Unlock()

	c.deviceState.Store(deviceIdle)
	c.reportDeviceStatus()

	// 若会话已被 ForceCloseSession/preempt 强制结束，signaling 随后的
	// unbound 只做清理，不再重复上报 user_unbound（forced 事件已由
	// preemptAndWait 发出）。
	if c.hooks != nil && !ctx.preemptedByForce.Load() {
		c.hooks.OnSessionStopped(c.inst.DeviceSerial, c.inst.InstanceID,
			sessionID, "user_unbound")
	}

	logger.Info("session fully removed", "session_id", sessionID)
}

// ---------------------------------------------------------------------------
// Relay: query_status / preempt
// ---------------------------------------------------------------------------

// handleRelayPreempt handles a relay preempt request from a new browser
// before it opens the /ws/browser/ connection.
func (c *Controller) handleRelayPreempt(msg common.WsMsg) {
	c.mu.Lock()
	oldID := c.currentSessionID
	oldCtx := c.sessions[oldID]
	c.mu.Unlock()

	if oldCtx != nil {
		logger.Warn("relay preempt: stopping old session",
			"old_session", oldID)
		c.preemptAndWait(oldCtx, oldID, "forced")
	} else {
		logger.Info("relay preempt: no active session to preempt")
	}

	c.ws.Send(common.WsMsg{
		Type:    "relay",
		RelayID: msg.RelayID,
		Payload: map[string]any{
			"type": "preempt_resp",
			"ok":   true,
		},
	})
}

// preemptAndWait sends TypePreempted to the old browser, signals the old
// SessionCtx to stop via stopChan, and waits for cleanup with a timeout.
// reason 透传到 SessionStopped 事件（relay/bound preempt 传 "forced"）。
func (c *Controller) preemptAndWait(ctx *SessionCtx, sessionID, reason string) {
	// Mark as force-preempted: a subsequent signaling unbound (triggered by
	// the browser WS being closed) must NOT also emit user_unbound.
	ctx.preemptedByForce.Store(true)

	// Notify old browser — signaling will forward this to the old browser WS
	c.ws.Send(common.WsMsg{Type: common.TypePreempted, SessionID: sessionID})

	// Signal stop
	select {
	case <-ctx.stopChan:
		// already stopped
	default:
		close(ctx.stopChan)
	}

	// Wait for cleanup with timeout
	select {
	case <-ctx.done:
		logger.Info("old session cleaned up", "session_id", sessionID)
	case <-time.After(preemptTimeout):
		logger.Warn("old session cleanup timeout, forcing removal",
			"session_id", sessionID)
	}

	// Remove from map
	c.mu.Lock()
	delete(c.sessions, sessionID)
	if c.currentSessionID == sessionID {
		c.currentSessionID = ""
	}
	c.mu.Unlock()

	c.deviceState.Store(deviceIdle)
	c.reportDeviceStatus()

	if c.hooks != nil {
		c.hooks.OnSessionStopped(c.inst.DeviceSerial, c.inst.InstanceID,
			sessionID, reason)
	}
}

