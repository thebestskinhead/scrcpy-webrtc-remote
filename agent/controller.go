// shutdownAll stops all active SessionCtx goroutines.
func (c *Controller) shutdownAll() {
	c.mu.Lock()
	var ids []string
	for id, ctx := range c.sessions {
		ids = append(ids, id)
		logger.Info("shutting down session", "session_id", id)
		select {
		case <-ctx.stopChan:
		default:
			close(ctx.stopChan)
		}
	}

	// Clear all state
	c.sessions = make(map[string]*SessionCtx)
	c.currentSessionID = ""
	c.deviceState.Store(deviceIdle)
	c.mu.Unlock()

	// 事件上报放锁外（hooks 实现可能回调，避免持 c.mu 递归）。
	if c.hooks != nil {
		for _, id := range ids {
			c.hooks.OnSessionStopped(c.inst.DeviceSerial, c.inst.InstanceID, id, "agent_stop")
		}
		c.reportDeviceStatus()
	}
}

