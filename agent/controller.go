func getUint64PointerID(m map[string]any, key string) uint64 {
	if m == nil {
		return gateway.PointerIDGenericFinger
	}
	v, ok := m[key]
	if !ok {
		return gateway.PointerIDGenericFinger
	}
	switch val := v.(type) {
	case float64:
		return uint64(int64(val))
	case int64:
		return uint64(val)
	case int:
		return uint64(val)
	default:
		return gateway.PointerIDGenericFinger
	}
}

func getFloat64(m map[string]any, key string) float64 {
	if m == nil {
		return 0
	}
	v, ok := m[key]
	if !ok {
		return 0
	}
	switch val := v.(type) {
	case float64:
		return val
	case int:
		return float64(val)
	case bool:
		if val {
			return 1
		}
		return 0
	default:
		return 0
	}
}

func toUint32(v any) (uint32, bool) {
	switch val := v.(type) {
	case float64:
		return uint32(val), true
	case uint32:
		return val, true
	case int:
		return uint32(val), true
	default:
		return 0, false
	}
}
